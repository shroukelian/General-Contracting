document.addEventListener('DOMContentLoaded', () => {
    const langBtn = document.getElementById('lang-switch');
    const menuToggle = document.getElementById('mobile-menu-icon');
    const dropdownMenu = document.getElementById('mobile-dropdown');
    const closeDropdown = document.querySelector('.close-dropdown-btn');
    const navLinks = document.querySelectorAll('.nav-links a, .dropdown-content a');
    const sections = document.querySelectorAll('section');
    let currentLang = 'ar';
    const updateLanguage = () => {
        document.documentElement.lang = currentLang;
        document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
        langBtn.textContent = currentLang === 'ar' ? 'EN' : 'AR';
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[currentLang][key]) el.textContent = translations[currentLang][key];
        });

        document.querySelectorAll('[data-i18n-holder]').forEach(el => {
            const key = el.getAttribute('data-i18n-holder');
            if (translations[currentLang][key]) el.placeholder = translations[currentLang][key];
        });
    };

    langBtn.addEventListener('click', () => {
        currentLang = currentLang === 'ar' ? 'en' : 'ar';
        updateLanguage();
    });
    if (menuToggle) {
        menuToggle.addEventListener('click', (e) => {
            e.stopPropagation();
            dropdownMenu.classList.add('open');
            document.body.style.overflow = 'hidden'; 
        });
    }

    const hideDropdown = () => {
        dropdownMenu.classList.remove('open');
        document.body.style.overflow = 'auto';
    };

    if (closeDropdown) {
        closeDropdown.addEventListener('click', hideDropdown);
    }
    document.querySelectorAll('.dropdown-content a').forEach(link => {
        link.addEventListener('click', hideDropdown);
    });
    const filterBtns = document.querySelectorAll('.filter-btn');
    const portfolioItems = document.querySelectorAll('.portfolio-item');

    filterBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            filterBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            const val = btn.getAttribute('data-filter');

            portfolioItems.forEach(item => {
                if (val === 'all' || item.classList.contains(val)) {
                    item.classList.remove('hide');
                    item.classList.add('show');
                } else {
                    item.classList.remove('show');
                    item.classList.add('hide');
                }
            });
        });
    });
    const waForm = document.getElementById('whatsapp-form');
    if (waForm) {
        waForm.addEventListener('submit', (e) => {
            e.preventDefault();
            const name = document.getElementById('name').value;
            const service = document.getElementById('service-select').value;
            const msg = document.getElementById('message').value;
            const phone = "966543595461";
            const fullMsg = `مرحباً، أنا ${name}. أرغب في استشارة لخدمة: ${service}. التفاصيل: ${msg}`;
            window.open(`https://wa.me/${phone}?text=${encodeURIComponent(fullMsg)}`, '_blank');
        });
    }
    const handleScroll = () => {
        const scrollY = window.pageYOffset;
        const floatingNav = document.querySelector('.floating-nav');
        if (floatingNav) {
            if (scrollY > 50) {
                floatingNav.style.background = "rgba(10, 10, 10, 0.98)";
                floatingNav.style.padding = "10px 30px";
            } else {
                floatingNav.style.background = "rgba(10, 10, 10, 0.6)";
                floatingNav.style.padding = "15px 30px";
            }
        }
        let currentId = "";
        sections.forEach(section => {
            const sectionTop = section.offsetTop - 250;
            const sectionHeight = section.clientHeight;
            if (scrollY >= sectionTop && scrollY < sectionTop + sectionHeight) {
                currentId = section.getAttribute('id');
            }
        });

        navLinks.forEach(link => {
            link.classList.remove('active');
            if (link.getAttribute('href') === `#${currentId}`) {
                link.classList.add('active');
            }
        });
        document.querySelectorAll('.reveal-right, .reveal-left, .fade-up, .animate-box').forEach(el => {
            if (el.getBoundingClientRect().top < window.innerHeight - 100) {
                el.classList.add('active-reveal');
            }
        });
    };

    window.addEventListener('scroll', handleScroll);
    handleScroll(); 
    updateLanguage(); 
});